"""Prepare Quarto include fragments from retained checked files only."""

from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import json
import math
import os
from pathlib import Path
import tempfile


# Units are written as TeX so HTML and PDF views typeset them as mathematics.
PER_SECOND = r"$\mathrm{s^{-1}}$"
SECOND = r"$\mathrm{s}$"
DEGREE_CELSIUS = r"$^{\circ}\mathrm{C}$"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def refuse(message: str) -> None:
    raise SystemExit(f"present refused retained outputs: {message}")


def tex_number(value: float, digits: int = 4) -> str:
    """Format a finite value as TeX with ``digits`` significant figures."""
    if not math.isfinite(value):
        refuse(f"non-finite retained value {value!r}")
    mantissa, exponent = f"{value:.{digits - 1}e}".split("e")
    exponent = int(exponent)
    if -2 <= exponent <= 3:
        return f"{value:.{max(digits - 1 - exponent, 0)}f}"
    return rf"{mantissa} \times 10^{{{exponent}}}"


def inline_math(value: str) -> str:
    return f"${value}$"


def parameter_table(summary: dict) -> list[str]:
    fit, parameters = summary["fit"], summary["parameters"]
    low, high = fit["cooling_rate_ci95_per_s"]
    # Rate columns share one power of ten in the header so the cells stay plain numbers.
    rate = fit["cooling_rate_per_s"]
    power = math.floor(math.log10(abs(rate))) if rate else 0
    scale = 10.0 ** -power
    rate_unit = rf"10^{{{power}}}\,\mathrm{{s^{{-1}}}}" if power else r"\mathrm{s^{-1}}"
    columns = [
        (r"k", rate_unit, tex_number(rate * scale)),
        (r"s_k", rate_unit, tex_number(fit["cooling_rate_standard_error_per_s"] * scale, 2)),
        (r"\mathrm{CI}_{95}(k)", rate_unit, f"[{tex_number(low * scale)},\\ {tex_number(high * scale)}]"),
        (r"1/k", r"\mathrm{s}", tex_number(fit["time_constant_s"])),
        (r"\mathrm{RMSE}", r"^{\circ}\mathrm{C}", tex_number(fit["residual_rmse_degC"], 3)),
        (r"T_a", r"^{\circ}\mathrm{C}", tex_number(parameters["ambient_temperature_degC"], 3)),
        (r"T_0", r"^{\circ}\mathrm{C}", tex_number(parameters["initial_temperature_degC"], 3)),
        (r"n\,/\,\nu", None, f"{fit['observation_count']}\\,/\\,{fit['degrees_of_freedom']}"),
    ]
    # One math group per header keeps the symbol and unit on one line.
    header = [f"${symbol}$" if unit is None else f"${symbol}\\ \\left({unit}\\right)$" for symbol, unit, _ in columns]
    return [
        "| " + " | ".join(header) + " |",
        "| " + " | ".join("---:" for _ in columns) + " |",
        "| " + " | ".join(f"${value}$" for *_, value in columns) + " |",
    ]


PARAMETER_CAPTION = (
    "Fitted cooling rate $k$ with its linearized standard error $s_k$ and 95 % Student-$t$ interval "
    "$\\mathrm{CI}_{95}(k)$; derived time constant $1/k$; residual RMSE; fixed ambient and initial temperatures "
    "$T_a$ and $T_0$; $n$ observations and $\\nu$ residual degrees of freedom."
)


def data_table(curve_path: Path) -> list[str]:
    with curve_path.open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    header = [
        f"| time ({SECOND}) | observed ({DEGREE_CELSIUS}) | fitted ({DEGREE_CELSIUS}) | residual ({DEGREE_CELSIUS}) |",
        "| ---: | ---: | ---: | ---: |",
    ]
    return header + [
        "| {:g} | {:.3f} | {:.3f} | {:+.3f} |".format(
            float(row["time_s"]), float(row["observed_temperature_degC"]),
            float(row["fitted_temperature_degC"]), float(row["residual_degC"]),
        )
        for row in rows
    ]


def check_lines(summary: dict) -> tuple[str, list[str]]:
    fit, checks = summary["fit"], summary["checks"]
    verdict = "passed" if all(checks.values()) else "not passed; diagnose before any negative disposition (failure-triage)"
    lines = [
        f"- Residual RMSE {inline_math(tex_number(fit['residual_rmse_degC'], 3))} {DEGREE_CELSIUS} "
        f"against the data-scaled bound {inline_math(tex_number(fit['rmse_bound_degC'], 3))} {DEGREE_CELSIUS}: "
        f"**{'passed' if checks['rmse_below_data_scaled_bound'] else 'not passed'}**.",
        f"- Refit from a second initial guess differs by {inline_math(tex_number(fit['refit_difference_per_s'], 2))} {PER_SECOND} "
        f"against the tolerance {inline_math(tex_number(fit['refit_tolerance_per_s'], 2))} {PER_SECOND}: "
        f"**{'passed' if checks['refit_consistent'] else 'not passed'}**.",
    ]
    return verdict, lines


def include_fragment(summary: dict, curve_path: Path, figure_path: Path, residual_path: Path) -> str:
    verdict, lines = check_lines(summary)
    callout = "note" if all(summary["checks"].values()) else "warning"
    return "\n".join([
        "<!-- Generated by scripts/present.py from the hash-checked retained set. -->",
        "",
        *parameter_table(summary),
        "",
        f": {PARAMETER_CAPTION} {{#tbl-cooling-parameters}}",
        "",
        "::: {.panel-tabset}",
        "",
        "## Fit",
        "",
        f"![Observed temperatures (points) and the one-parameter fit (line).]({figure_path.as_posix()}){{#fig-cooling-fit}}",
        "",
        "## Residuals",
        "",
        f"![Residuals $T_\\mathrm{{obs}} - T_\\mathrm{{fit}}$ at each observation time.]({residual_path.as_posix()}){{#fig-cooling-residuals}}",
        "",
        "## Data",
        "",
        *data_table(curve_path),
        "",
        f": Retained observations, fitted values, and residuals from `{curve_path.as_posix()}`. {{#tbl-cooling-data}}",
        "",
        ":::",
        "",
        f"::: {{.callout-{callout}}}",
        f"## Numerical checks: {verdict}",
        "",
        *lines,
        "",
        "These checks verify the fit to these observations; they do not validate the model physically.",
        ":::",
        "",
    ])


def values_fragment(summary: dict) -> str:
    """Return a YAML metadata block; ``{{< meta cooling-fit.* >}}`` quotes it inline."""
    fit = summary["fit"]
    verdict, _ = check_lines(summary)
    values = {
        "rate": inline_math(f"k = {tex_number(fit['cooling_rate_per_s'])}\\ \\mathrm{{s^{{-1}}}}"),
        "rate-standard-error": inline_math(f"{tex_number(fit['cooling_rate_standard_error_per_s'], 2)}\\ \\mathrm{{s^{{-1}}}}"),
        "time-constant": inline_math(f"1/k = {tex_number(fit['time_constant_s'])}\\ \\mathrm{{s}}"),
        "rmse": inline_math(f"{tex_number(fit['residual_rmse_degC'], 3)}\\ ^{{\\circ}}\\mathrm{{C}}"),
        "observations": str(fit["observation_count"]),
        "checks": verdict,
    }
    # A JSON string is a valid YAML double-quoted scalar, so values need no YAML escaping.
    lines = [f"  {key}: {json.dumps(value)}" for key, value in values.items()]
    return "\n".join(["---", "cooling-fit:", *lines, "---", ""])


def provenance_fragment(summary: dict, summary_path: Path, paths: dict[str, Path], helper_path: Path) -> str:
    rows = [f"| [`{summary_path.as_posix()}`]({summary_path.as_posix()}) | retained summary | -- |"]
    for name, path in paths.items():
        rows.append(f"| [`{path.as_posix()}`]({path.as_posix()}) | {name.replace('_', ' ')} | "
                    f"`{summary['generated_files'][name]['sha256'][:12]}` |")
    for name, digest in sorted(summary["inputs"].items()):
        rows.append(f"| {name.removesuffix('_sha256')} | calculation input | `{digest[:12]}` |")
    environment = summary["environment"]
    packages = ", ".join(f"{name} {version}" for name, version in sorted(environment["packages"].items()))
    return "\n".join([
        "<!-- Generated by scripts/present.py from the hash-checked retained set. -->",
        "",
        "| file | role | SHA-256 (first 12) |",
        "| --- | --- | --- |",
        *rows,
        "",
        ": Retained files with download links and the hashes present verified before writing this page.",
        "",
        f"Calculation environment: Python {environment['python']}; {packages}.",
        "",
        '::: {.callout-note collapse="true"}',
        f"## Model source: `{helper_path.name}` (verified against the retained hash)",
        "",
        "```python",
        helper_path.read_text(encoding="utf-8").rstrip("\n"),
        "```",
        ":::",
        "",
    ])


def views_notebook(summary: dict, figure_path: Path, residual_path: Path) -> str:
    """Return a non-executable notebook of labeled retained views for ``{{< embed >}}``."""
    def figure_cell(label: str, caption: str, path: Path) -> dict:
        return {
            "cell_type": "code", "id": label, "metadata": {}, "execution_count": None,
            "source": [f"#| label: {label}\n", f"#| fig-cap: {json.dumps(caption)}\n",
                       f"# Retained file {path.as_posix()} (sha256 {sha256(path)})"],
            "outputs": [{"output_type": "display_data", "metadata": {}, "data": {
                "image/png": base64.b64encode(path.read_bytes()).decode(),
                "text/plain": [f"<retained figure {path.as_posix()}>"],
            }}],
        }

    table = "\n".join(parameter_table(summary)) + "\n"
    cells = [
        # Quarto would otherwise try to run these cells under an executing profile.
        {"cell_type": "raw", "id": "front-matter", "metadata": {},
         "source": ["---\n", "title: Retained cooling-fit views\n", "execute:\n", "  enabled: false\n", "---\n"]},
        figure_cell("fig-cooling-fit", "Observed temperatures (points) and the one-parameter fit (line).", figure_path),
        figure_cell("fig-cooling-residuals", "Residuals of the one-parameter fit at each observation time.", residual_path),
        {"cell_type": "code", "id": "tbl-cooling-parameters", "metadata": {}, "execution_count": None,
         "source": ["#| label: tbl-cooling-parameters\n",
                    f"#| tbl-cap: {json.dumps(PARAMETER_CAPTION)}\n",
                    "# Retained summary results/fit_summary.json"],
         "outputs": [{"output_type": "display_data", "metadata": {},
                      "data": {"text/markdown": table, "text/plain": [table]}}]},
    ]
    notebook = {
        "nbformat": 4, "nbformat_minor": 5, "cells": cells,
        "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"},
                     "language_info": {"name": "python"}},
    }
    return json.dumps(notebook, indent=1) + "\n"


def write_if_changed(path: Path, content: str) -> None:
    data = content.encode()
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix=f".{path.name}.", delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(data)
    os.replace(temporary, path)


def present(args: argparse.Namespace) -> None:
    input_paths = {
        "observations_sha256": Path(args.observations),
        "parameters_sha256": Path(args.parameters),
        "environment_sha256": Path(args.environment),
        "script_sha256": Path(args.script),
        "helper_sha256": Path(args.helper),
    }
    summary_path = Path(args.summary)
    generated_paths = {
        "curve": Path(args.curve),
        "figure": Path(args.figure),
        "residual_figure": Path(args.residual_figure),
    }
    if not summary_path.is_file():
        refuse(f"missing {summary_path}; run calculate before present")

    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    if summary.get("complete") is not True:
        refuse(f"{summary_path} is not marked complete")
    retained_inputs = summary.get("inputs", {})
    for name, path in input_paths.items():
        if not path.is_file():
            refuse(f"missing current input {path}")
        if sha256(path) != retained_inputs.get(name):
            refuse(f"{path} changed after the retained calculation; run calculate before present")
    checks = summary.get("checks", {})
    if not checks or not all(isinstance(value, bool) for value in checks.values()):
        refuse("the retained numerical checks are missing or malformed")

    generated = summary.get("generated_files", {})
    for name, path in generated_paths.items():
        record = generated.get(name, {})
        if record.get("path") != path.as_posix():
            refuse(f"{name} path does not match the retained summary")
        if not path.is_file():
            refuse(f"missing {path}")
        if sha256(path) != record.get("sha256"):
            refuse(f"{path} does not match the retained summary hash")

    required = (
        "cooling_rate_per_s", "cooling_rate_standard_error_per_s", "cooling_rate_ci95_per_s",
        "time_constant_s", "residual_rmse_degC", "rmse_bound_degC", "refit_difference_per_s",
        "refit_tolerance_per_s", "observation_count", "degrees_of_freedom",
    )
    fit = summary.get("fit", {})
    if any(fit.get(quantity) is None for quantity in required) or not {
        "rmse_below_data_scaled_bound", "refit_consistent"} <= checks.keys():
        refuse("the retained fit is missing a required quantity or check")

    figure, residual = generated_paths["figure"], generated_paths["residual_figure"]
    write_if_changed(Path(args.output), include_fragment(summary, generated_paths["curve"], figure, residual))
    write_if_changed(Path(args.values), values_fragment(summary))
    write_if_changed(Path(args.provenance), provenance_fragment(
        summary, summary_path, generated_paths, input_paths["helper_sha256"]))
    write_if_changed(Path(args.views), views_notebook(summary, figure, residual))


def main() -> int:
    parser = argparse.ArgumentParser()
    for name in ("observations", "parameters", "environment", "script", "helper", "summary",
                 "curve", "figure", "residual-figure", "output", "values", "provenance", "views"):
        parser.add_argument(f"--{name}", required=True)
    present(parser.parse_args())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
