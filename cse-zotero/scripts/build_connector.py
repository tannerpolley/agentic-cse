"""Copy the official Connector with a separate identity and the agent-job module."""
from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

EXTENSION_ID = "ekhagklcjbdpajgpjgmbionohlpdbjgc"
OUTPUT = Path.home() / ".local/share/cse/zotero/zotero-connector-agent"


def build(source=None, output=OUTPUT):
    if source is None:
        root = Path.home() / f".config/google-chrome/Default/Extensions/{EXTENSION_ID}"
        versions = list(root.glob("*/manifest.json"))
        if not versions:
            raise ValueError("Official Zotero Connector is not installed in everyday Chrome")
        source = max(versions, key=lambda p: tuple(map(int, json.loads(p.read_text())["version"].split(".")))).parent
    source, output = Path(source).resolve(), Path(output).resolve()
    if source == output or source in output.parents or output in source.parents:
        raise ValueError("Connector output must be separate from the official source")
    module = (Path(__file__).resolve().parents[1] / "zotero-plugin/connector-agent.js").read_bytes()
    supported = re.search(rb'CONNECTOR_VERSION = "([^"]+)"', module)[1].decode()
    revision = int(re.search(rb'MODULE_REVISION = (\d+)', module)[1])
    manifest = json.loads((source / "manifest.json").read_text())
    version = manifest["version"]
    if version != supported:
        raise ValueError(f"Connector version mismatch: installed {version}, agent module supports {supported}; inspect the new native APIs before rebuilding")
    if output.exists():
        shutil.rmtree(output)
    # Store-generated compiled rules are regenerated by Chrome for unpacked extensions.
    shutil.copytree(source, output, ignore=shutil.ignore_patterns("_metadata"))
    manifest.pop("key", None)
    manifest["name"] = "Zotero Connector (agent)"
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (output / "connector-agent.js").write_bytes(module)
    (output / "cse-agent-job.html").write_text('<!doctype html><meta charset="utf-8"><title>Saving paper to Zotero</title>\n')
    with (output / "background-worker.js").open("ab") as worker:
        worker.write(b'\nimportScripts("connector-agent.js");\n')
    (output / "cse-agent-build.json").write_text(json.dumps({"module_revision": revision}) + "\n")
    return {"version": version, "module_revision": revision, "output": str(output), "modified": ["manifest.json", "background-worker.js"], "added": ["connector-agent.js", "cse-agent-job.html", "cse-agent-build.json"]}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    try:
        print(json.dumps(build(args.source, args.output), indent=2))
    except (OSError, ValueError) as error:
        parser.exit(1, str(error) + "\n")
